No software or license is needed on your side: MolMeDB runs the whole calculation. You choose one of the prepared membranes, a method, a temperature and up to {{ $limits['max_molecules'] }} molecules, and the workflow computes their passive interaction values. Finished results become part of MolMeDB.

## What molecules can be calculated

The workflow accepts organic, drug-like molecules. A molecule is rejected when:

- it has more than {{ $limits['max_atoms'] }} atoms, hydrogens included;
- it contains other elements than {{ implode(', ', $limits['allowed_elements']) }};
- it is not a single connected molecule (salts and mixtures, written with a dot in SMILES, are not supported).

## How to run predictions

### Step 1: Sign in

Log in with your account, or verify your e-mail right on the page with a one-time code (an account is created for you). Both lead to the same account, so you can always come back to your calculations. See [Uploading your data](/docs/contributing-data/uploading-your-data) for details.

### Step 2: Select a membrane

Choose a membrane from the cards. Only membranes the workflow can calculate are offered, not all membranes of MolMeDB; *show more* opens the details of a membrane.

### Step 3: Select a method

Choose one of the computational methods.

### Step 4: Set the temperature

Enter a temperature from {{ $limits['temperature']['min'] }} to {{ $limits['temperature']['max'] }} °C ({{ $limits['temperature']['default'] }} °C by default).

### Step 5: Enter your molecules

Paste the molecules as SMILES, one per line, at most {{ $limits['max_molecules'] }}. The limits above are also shown on the page, as the server checks them.

### Step 6: Add a description

A short description of at most {{ $limits['description_length'] }} characters, only for you, to tell your submissions apart.

### Step 7: Validate

Click *Validate*. The membrane, method, temperature and description are checked, and the SMILES are canonicalized and checked against the limits above. Duplicate molecules are skipped, and you see how many. Problems are listed in a dialog; fix them and validate again.

### Step 8: Submit

*Submit* becomes active after a successful validation. The calculation is queued and you are taken to its tracking page.

### Step 9: Follow the progress

[Laboratory → Running predictions](/lab/running-predictions) lists all your submissions. Every molecule goes through these states:

| State | Meaning |
|---|---|
| Prepared | Queued, waiting for a worker. |
| Running | Being calculated. |
| Paused | Picked up, but paused by the computing cluster. |
| Finished | Done; the results are available. |
| Error | The calculation of this molecule failed. |

## How the calculation works

The workflow takes a SMILES and goes through the steps below; each step starts when the previous one is finished.

1. **Canonicalization.** [RDKit](https://www.rdkit.org) canonicalizes the SMILES, which then identifies the molecule throughout the workflow. If the molecule was calculated before, steps 2 to 5 are skipped.
2. **Initial 3D structure (RDKit).** Hydrogens are added, 3D coordinates are generated by the ETKDGv3 method and relaxed by the MMFF94 force field (UFF when MMFF94 parameters are missing). The result is checked to be a true 3D structure; its formal charge and multiplicity are passed to the next steps. This takes seconds.
3. **Conformer search (ORCA GOAT).** The GOAT algorithm of ORCA explores the conformations and keeps up to six low-energy conformers that cover their diversity. From here on, every conformer is processed on its own. Typically 30 minutes to 2 hours.
4. **Geometry optimization (ORCA).** Every conformer is optimized at the BP86/def2-TZVPD level in Cartesian coordinates, in parallel; the molecule waits for the slowest one. Typically 30 minutes to 3 hours per conformer.
5. **Geometry handoff.** The optimized geometry is passed to the COSMO step. A further TURBOMOLE optimization is not run: the ORCA geometry is accurate enough for the COSMO calculation, and the optimization would cost more than it brings.
6. **COSMO and COSMOtherm.** For every conformer, TURBOMOLE computes the COSMO surface (`define`, `cosmoprep` with the def2-TZVPD basis, the B-P functional and 162 surface points, and a `ridft` single point), giving a `.ccf` file with the surface charge density. COSMOtherm then computes the transport through the membrane from the `.ccf` files of all conformers and a `.mic` file describing the membrane: permeability, partitioning and related quantities at the chosen temperature. Typically 15 to 60 minutes.

### Reuse of results

The `.ccf` files of a molecule are kept. A molecule calculated before with another membrane or temperature needs only step 6 again, which is much faster.

## Infrastructure and capacity

The calculations run on the e-INFRA CZ infrastructure, on a Kubernetes cluster of CERIT-SC within the Czech national research network MetaCentrum (CESNET). We thank both institutions for the computational resources, provided by the e-INFRA CZ project (ID:90254) supported by the Ministry of Education, Youth and Sports of the Czech Republic.

| Resource | Amount |
|---|---|
| CPU cores | 380 |
| RAM | 580 GiB |

The resources are shared by all steps and the database server. These workers run in parallel:

| Step | Parallel workers |
|---|---|
| Conformer search (GOAT) | 45 |
| Geometry optimization (ORCA) | 145 |
| COSMO calculations (COSMOtherm) | 8 |

The throughput depends on the size and flexibility of the molecules; the geometry optimization is the slowest step:

- small, rigid molecules (MW up to about 300): hundreds of molecules per day;
- typical drug-like molecules (MW 300 to 500, 3 to 6 conformers): 100 to 500 molecules per day;
- larger or very flexible molecules: tens of molecules per day.

> [!WARNING]
> When the cluster is fully loaded, a calculation can wait in the queue for several days. Submissions are processed in the order they arrive.
